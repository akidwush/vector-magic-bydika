for (const [name, shape] of Object.entries(shapes)) {
  const background =
    name === "transparent"
      ? ""
      : '<rect width="128" height="128" fill="white"/>';
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="128" height="128">${background}${shape}</svg>`;
  let image = sharp(Buffer.from(svg));
  if (name === "icon") image = image.threshold(128);
  // Render icon and corners at native resolution; anti-alias on curves intentionally retained.
  await image.png().toFile(`tests/fixtures/${name}.png`);
  if (name === "illustration")
    await image.webp().toFile("tests/fixtures/illustration.webp");
}
const pixels = Buffer.alloc(128 * 128 * 3);
let seed = 42;
for (let y = 0; y < 128; y++)
  for (let x = 0; x < 128; x++) {
    seed = (1664525 * seed + 1013904223) >>> 0;
    const noise = (seed >>> 28) - 8;
    const i = (y * 128 + x) * 3;
    pixels[i] = Math.max(0, Math.min(255, x * 2 + noise));
    pixels[i + 1] = Math.max(0, Math.min(255, y * 2 + noise));
    pixels[i + 2] = 90;
  }
await sharp(pixels, { raw: { width: 128, height: 128, channels: 3 } })
  .jpeg({ quality: 85 })
  .toFile("tests/fixtures/gradient.jpg");
