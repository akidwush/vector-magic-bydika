import sharp from "sharp";
import { mkdir, writeFile } from "node:fs/promises";
const root = "tests/fixtures/coverage";
await mkdir(root, { recursive: true });
const cases = {
  circle: '<circle cx="63.35" cy="64.2" r="35.7" fill="#df3d34"/>',
  oval: '<ellipse cx="64.2" cy="63.4" rx="39.3" ry="22.7" fill="#2456ae"/>',
  diagonal:
    '<path d="M18.3 108.7L109.4 19.2" stroke="#24313a" stroke-width="1.6"/>',
  triangle: '<path d="M17.3 108.2L63.6 17.7L111.4 108.2Z" fill="#c84032"/>',
  pink: '<rect x="13.25" y="18.4" width="98.2" height="91.3" fill="#d63238"/><rect x="70.3" y="31.6" width="22.4" height="60.3" fill="#ff8080"/>',
};
for (const [name, art] of Object.entries(cases)) {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="128" height="128"><rect width="128" height="128" fill="white"/>${art}</svg>`;
  await writeFile(`${root}/${name}.svg`, svg);
  await sharp(Buffer.from(svg)).png().toFile(`${root}/${name}.png`);
}
// Analytic box coverage for a known fractional vertical boundary in two color spaces.
const lin = (v) => (v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4);
const enc = (v) =>
  v <= 0.0031308 ? 12.92 * v : 1.055 * v ** (1 / 2.4) - 0.055;
for (const linear of [false, true]) {
  const data = Buffer.alloc(128 * 128 * 4);
  for (let y = 0; y < 128; y++)
    for (let x = 0; x < 128; x++) {
      const t = Math.max(0, Math.min(1, 63.25 - x));
      const a = [0.9, 0.1, 0.2],
        b = [0.1, 0.8, 0.9];
      for (let c = 0; c < 3; c++)
        data[(y * 128 + x) * 4 + c] = Math.round(
          (linear
            ? enc(t * lin(a[c]) + (1 - t) * lin(b[c]))
            : t * a[c] + (1 - t) * b[c]) * 255,
        );
      data[(y * 128 + x) * 4 + 3] = 255;
    }
  await sharp(data, { raw: { width: 128, height: 128, channels: 4 } })
    .png()
    .toFile(`${root}/edge-${linear ? "linear" : "srgb"}.png`);
}
await writeFile(
  `${root}/README.md`,
  "Original CC0 geometric fixtures generated by scripts/coverage-fixtures.mjs. SVGs are known vector ground truth; edges have analytic box coverage at x=63.25 in encoded-sRGB and linear-light. Intentional pink is a real 22.4px region, not AA to be discarded. No user or competitor assets.\n",
);
